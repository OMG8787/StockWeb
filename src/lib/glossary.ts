/** 比對用：所有寫法 → 條目。ASCII 寫法要求前後不是英數字（避免 KD 比到 KDJ、EPS 比到 EPSX）。 */
const BY_SURFACE = new Map<string, GlossaryEntry>();
for (const e of GLOSSARY) for (const s of [e.term, ...(e.aliases ?? [])]) BY_SURFACE.set(s, e);

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const surfaces = [...BY_SURFACE.keys()].sort((a, b) => b.length - a.length);
const isAscii = (s: string) => /^[\x20-\x7e]+$/.test(s);
const TERM_RE = new RegExp(
  surfaces.map((s) => (isAscii(s) ? `(?<![A-Za-z0-9])${escapeRe(s)}(?![A-Za-z0-9])` : escapeRe(s))).join("|"),
  "g",
);

export interface TermHit {
  start: number;
  end: number;
  entry: GlossaryEntry;
}

/** 找出一段文字裡所有名詞（由左到右，同一位置取最長的寫法） */
export function findTerms(text: string): TermHit[] {
  const out: TermHit[] = [];
  TERM_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = TERM_RE.exec(text))) {
    const entry = BY_SURFACE.get(m[0]);
    if (entry) out.push({ start: m.index, end: m.index + m[0].length, entry });
  }
  return out;
}

/** 這段文字裡有沒有名詞（掃整頁時先用它快速略過大部分文字） */
export function hasTerm(text: string): boolean {
  TERM_RE.lastIndex = 0;
  return TERM_RE.test(text);
}
